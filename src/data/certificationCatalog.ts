/**
 * Returns a catalog certification converted to a CertificationPreset format
 * so that students can register it with 1 click into their study workspace.
 */
export function catalogCertToPreset(cert: CatalogCertification): CertificationPreset {
  // Check if there is an existing JSON preset with richer export intro
  const existing = CERTIFICATION_PRESETS.find(
    (p) => p.code?.toLowerCase() === cert.code.toLowerCase()
  );
  if (existing) {
    return existing;
  }

  return {
    id: `preset-${cert.provider}-${cert.code.toLowerCase().replace(/[^a-z0-9]/g, '-')}`,
    name: cert.name,
    code: cert.code,
    version: '',
    color: cert.color,
    icon: cert.icon,
    examDurationMinutes: cert.examDurationMinutes,
    accommodationMinutes: cert.accommodationMinutes || 30,
    questionCount: 60,
    passingScore: '70% / Pass',
    description: cert.description,
    domains: cert.domains,
  };
}
